const { chromium } = require('playwright-core');
(async () => {
  const b = await chromium.launch({ executablePath: '/usr/bin/google-chrome', args: ['--no-sandbox'] });
  const p = await b.newPage(); const errs = [];
  p.on('pageerror', e => errs.push(e.message)); p.on('dialog', d => d.accept());
  await p.goto('http://localhost:8765/index.html');
  await p.click('#btnAdd');
  await p.fill('#editForm [name=name]', '编译原理'); await p.fill('#editForm [name=location]', 'X101');
  await p.selectOption('#editForm [name=day]', '3'); await p.selectOption('#editForm [name=start]', '3'); await p.selectOption('#editForm [name=end]', '4');
  await p.click('.quick-weeks [data-q=odd]');
  await p.click('#eSave');
  let s = await p.evaluate(() => TTApp.state().courses);
  console.log('added:', s.length, s[0].name, s[0].weeksText, s[0].day, s[0].start, s[0].end);
  await p.click('.course'); await p.click('#dEdit'); await p.fill('#editForm [name=weeks]', 'abc'); await p.click('#eSave');
  console.log('invalid weeks err:', await p.textContent('#eErr'));
  await p.fill('#editForm [name=weeks]', '1-8周'); await p.press('#editForm [name=weeks]', 'Enter'); await p.waitForTimeout(200);
  s = await p.evaluate(() => TTApp.state().courses); console.log('edited via Enter:', s[0].weeksText);
  await p.click('.course'); await p.click('#dDel'); await p.waitForTimeout(300);
  console.log('after delete:', await p.evaluate(() => TTApp.state().courses.length));
  await p.reload(); console.log('persisted settings ok:', await p.evaluate(() => !!JSON.parse(localStorage.getItem('timetable.v1')).settings.sectionTimes.length));
  console.log('errors:', errs); await b.close();
})();
